/*
 * Generates supabase/seed.sql with the PUBLIC content bank (content_items + content_versions).
 * The ranked pool is intentionally NOT exported: it lives only in the multiplayer server.
 * Usage: pnpm content:export
 */
import { writeFileSync } from 'node:fs';
import { CONTENT_ITEMS } from '../packages/content/src/index';

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const lines: string[] = ['-- Generated by scripts/export-content-sql.ts — do not edit by hand.', 'begin;'];
for (const i of CONTENT_ITEMS) {
  const tags = JSON.stringify(i.tags);
  lines.push(
    `insert into public.content_items (id, current_version, level, primary_skill, category, item_type, modes, tags, review_status, is_ranked_only) values (${q(i.id)}, ${i.version}, ${q(i.level)}, ${q(i.primarySkill)}, ${q(i.category)}, ${q(i.type)}, array[${i.modes.map(q).join(',')}]::text[], ${q(tags)}::jsonb, ${q(i.reviewStatus)}, false) on conflict (id) do update set current_version = excluded.current_version, level = excluded.level, tags = excluded.tags, review_status = excluded.review_status;`,
  );
  lines.push(`insert into public.content_versions (item_id, version, payload) values (${q(i.id)}, ${i.version}, ${q(JSON.stringify(i))}::jsonb) on conflict (item_id, version) do nothing;`);
}
lines.push('commit;');
writeFileSync('supabase/seed.sql', lines.join('\n') + '\n');
console.log(`Wrote supabase/seed.sql with ${CONTENT_ITEMS.length} public items.`);
